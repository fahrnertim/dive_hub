/** A boolean as SSI keeps it (1/0) or as the app sends it (true/false); anything else is unknown. */
export function asBool(v: unknown): boolean | null {
  if (v === true || v === 1 || v === '1') return true;
  if (v === false || v === 0 || v === '0') return false;
  return null;
}
